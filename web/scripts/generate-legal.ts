// Builds src/data/legal.ts from the owner's Word files in data/:
// terms-and-conditions.docx and privacy-policy.docx. Run: npm run gen:legal
//
// A .docx is a zip; word/document.xml holds the text. Each <w:p> is a
// paragraph, its style says whether it is a heading, and <w:numPr> marks a
// bullet. That is all these two documents use, so the reader stays small:
//
//   Heading1            → the page title (the first one; later ones become h2)
//   "Last updated: …"   → the date line under the title
//   Heading2 / Heading3 → section headings
//   bullets             → gathered into one list
//   anything else       → a paragraph
//
// Re-run it whenever the owner sends a new version of either document.

import { readFileSync, writeFileSync } from "node:fs";
import { unzipSync, strFromU8 } from "fflate";

export type LegalBlock =
  | { type: "p"; text: string }
  | { type: "h2"; text: string }
  | { type: "h3"; text: string }
  | { type: "ul"; items: string[] };

export type LegalDoc = { title: string; updated: string; blocks: LegalBlock[] };

const unescapeXml = (s: string) =>
  s
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'");

type Para = { style: string; bullet: boolean; text: string };

function paragraphs(file: URL): Para[] {
  const zip = unzipSync(new Uint8Array(readFileSync(file)));
  const xml = strFromU8(zip["word/document.xml"]!);
  return [...xml.matchAll(/<w:p\b[^>]*>([\s\S]*?)<\/w:p>/g)]
    .map((match) => {
      const body = match[1]!;
      const text = [...body.matchAll(/<w:t[^>]*>([\s\S]*?)<\/w:t>/g)]
        .map((t) => unescapeXml(t[1]!))
        .join("")
        .replace(/\s+/g, " ")
        .trim();
      return {
        style: (body.match(/<w:pStyle w:val="([^"]+)"/) ?? [])[1] ?? "",
        bullet: /<w:numPr>/.test(body),
        text,
      };
    })
    .filter((p) => p.text);
}

function toDoc(file: URL): LegalDoc {
  const paras = paragraphs(file);
  let title = "";
  let updated = "";
  const blocks: LegalBlock[] = [];

  for (const para of paras) {
    if (!title && para.style === "Heading1") {
      title = para.text;
      continue;
    }
    if (!updated && /^last updated/i.test(para.text)) {
      updated = para.text;
      continue;
    }
    if (para.bullet) {
      const last = blocks[blocks.length - 1];
      if (last?.type === "ul") last.items.push(para.text);
      else blocks.push({ type: "ul", items: [para.text] });
      continue;
    }
    if (para.style === "Heading3") blocks.push({ type: "h3", text: para.text });
    else if (/^Heading[12]$/.test(para.style)) blocks.push({ type: "h2", text: para.text });
    else blocks.push({ type: "p", text: para.text });
  }

  if (!title) throw new Error(`${file.pathname}: no Heading 1 to use as the title`);
  return { title, updated, blocks };
}

const docs = {
  terms: toDoc(new URL("../data/terms-and-conditions.docx", import.meta.url)),
  privacy: toDoc(new URL("../data/privacy-policy.docx", import.meta.url)),
};

const out = `// Generated by scripts/generate-legal.ts from the Word files in data/.
// Do not edit by hand: run \`npm run gen:legal\` after the owner sends a new version.

export type LegalBlock =
  | { type: "p"; text: string }
  | { type: "h2"; text: string }
  | { type: "h3"; text: string }
  | { type: "ul"; items: string[] };

export type LegalDoc = { title: string; updated: string; blocks: LegalBlock[] };

export const LEGAL_DOCS = ${JSON.stringify(docs, null, 2)} satisfies Record<string, LegalDoc>;

export type LegalSlug = keyof typeof LEGAL_DOCS;
`;

writeFileSync(new URL("../src/data/legal.ts", import.meta.url), out);

for (const [slug, doc] of Object.entries(docs)) {
  const sections = doc.blocks.filter((b) => b.type === "h2").length;
  console.log(`${slug}: "${doc.title}" — ${doc.blocks.length} blocks, ${sections} sections`);
}
